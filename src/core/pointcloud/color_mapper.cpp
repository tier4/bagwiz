ColorMapper::ColorMapper(ColorScheme scheme)
{
  switch (scheme) {
    case ColorScheme::kViridis:
      lut_ = kViridisLut;
      break;
    case ColorScheme::kTurbo:
      lut_ = kTurboLut;
      break;
    case ColorScheme::kJet:
      lut_ = kJetLut;
      break;
    case ColorScheme::kPlasma:
      lut_ = kPlasmaLut;
      break;
    case ColorScheme::kInferno:
      lut_ = kInfernoLut;
      break;
    case ColorScheme::kMagma:
      lut_ = kMagmaLut;
      break;
    case ColorScheme::kRainbow:
      lut_ = kRainbowLut;
      break;
  }
}

BgrColor ColorMapper::map(double value, double min, double max) const noexcept
{
  if (max <= min) {
    return lut_[0];
  }
  const double t = std::clamp((value - min) / (max - min), 0.0, 1.0);
  const std::size_t idx = static_cast<std::size_t>(std::lround(t * 255.0));
  return lut_[idx];
}

